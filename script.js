const state = { page:'home', filter:'All', lightboxIndex:0 };

function showPage(name){
  document.querySelectorAll('.page').forEach(p=>p.classList.remove('active'));
  document.getElementById('page-'+name).classList.add('active');
  document.querySelectorAll('.nav-btn').forEach(b=>b.classList.remove('active'));
  document.querySelector(`[data-page="${name}"]`).classList.add('active');
  state.page=name;
  window.scrollTo({top:0,behavior:'instant'});
  setTimeout(reveal,80);
}

function renderGallery(filter='All'){
  const root=document.getElementById('memory-grid');
  root.innerHTML='';
  galleryData.forEach((m,i)=>{
    if(filter!=='All' && m.category!==filter) return;
    const el=document.createElement('article');
    el.className='memory reveal';
    el.dataset.index=i;
    el.innerHTML=`<img src="${m.src}" alt="Chanda — memory ${i+1}" loading="lazy">
      <div class="memory-info"><div class="memory-number">MEMORY ${String(i+1).padStart(2,'0')}</div><div class="memory-caption">${m.caption}</div></div>`;
    el.addEventListener('click',()=>openLightbox(i));
    root.appendChild(el);
  });
  reveal();
}

function setFilter(filter,button){
  state.filter=filter;
  document.querySelectorAll('.filter').forEach(b=>b.classList.remove('active'));
  button.classList.add('active');
  renderGallery(filter);
}

function openLightbox(i){
  state.lightboxIndex=i;
  updateLightbox();
  document.getElementById('lightbox').classList.add('open');
  document.body.classList.add('lock');
}
function closeLightbox(){
  document.getElementById('lightbox').classList.remove('open');
  document.body.classList.remove('lock');
}
function updateLightbox(){
  const m=galleryData[state.lightboxIndex];
  document.getElementById('lb-img').src=m.src;
  document.getElementById('lb-caption').textContent=m.caption;
}
function moveLightbox(dir){
  state.lightboxIndex=(state.lightboxIndex+dir+galleryData.length)%galleryData.length;
  updateLightbox();
}

document.addEventListener('keydown',e=>{
  if(!document.getElementById('lightbox').classList.contains('open')) return;
  if(e.key==='Escape') closeLightbox();
  if(e.key==='ArrowRight') moveLightbox(1);
  if(e.key==='ArrowLeft') moveLightbox(-1);
});

function reveal(){
  document.querySelectorAll('.reveal').forEach(el=>{
    const r=el.getBoundingClientRect();
    if(r.top < innerHeight-45) el.classList.add('visible');
  });
}
addEventListener('scroll',reveal,{passive:true});

const canvas=document.getElementById('stars'),ctx=canvas.getContext('2d');
let stars=[];
function resizeStars(){canvas.width=innerWidth;canvas.height=innerHeight}
function initStars(){
  resizeStars(); stars=Array.from({length:Math.min(180,Math.floor(innerWidth/7))},()=>({
    x:Math.random(),y:Math.random(),r:Math.random()*1.25+.2,p:Math.random()*6.28,s:.0015+Math.random()*.004
  }));
}
function drawStars(t){
  ctx.clearRect(0,0,canvas.width,canvas.height);
  for(const s of stars){
    const a=.18+.55*(.5+.5*Math.sin(t*s.s+s.p));
    ctx.fillStyle=`rgba(255,255,255,${a})`;
    ctx.beginPath();ctx.arc(s.x*canvas.width,s.y*canvas.height,s.r,0,Math.PI*2);ctx.fill();
  }
  requestAnimationFrame(drawStars);
}
addEventListener('resize',resizeStars);
initStars();requestAnimationFrame(drawStars);

